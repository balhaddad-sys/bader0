#!/usr/bin/env bash
# Regenerates fonts.css (Inter variable, Latin subset, embedded as a data URI) and the OFL licence file.
# Embedding avoids any network/CDN request and any file:// origin issues in the Android WebView.
set -euo pipefail
cd "$(dirname "$0")/.."
T="$(mktemp -d)"; trap 'rm -rf "$T"' EXIT
( cd "$T" && npm pack @fontsource-variable/inter --silent >/dev/null && tar xzf fontsource-variable-inter-*.tgz )
B64="$(base64 -w0 "$T/package/files/inter-latin-wght-normal.woff2")"
cat > fonts.css <<CSS
/* Inter variable (Latin) — © The Inter Project Authors, SIL Open Font License 1.1 (see fonts-OFL.txt).
   Generated by tools/make-fonts-css.sh; embedded so the app makes no network requests. */
@font-face {
  font-family: "Inter";
  font-style: normal;
  font-weight: 100 900;
  font-display: swap;
  src: url(data:font/woff2;base64,$B64) format("woff2");
}
CSS
cp "$T/package/LICENSE" fonts-OFL.txt
echo "fonts.css: $(du -h fonts.css | cut -f1)"
